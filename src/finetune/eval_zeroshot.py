"""Zero-shot LLM judges on the held-out test set (the honest comparison rows).

Judges each test pair with Groq Llama and Gemini Flash (batch 5 pairs/request),
reports macro-F1 + per-class F1 + a cross-generator breakdown (each judge's F1
on pairs generated by the OTHER model are the contamination-clean cells).
Writes results/metrics_zeroshot_<provider>.json.
"""
import json
import re
import sys
import time
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.append(str(ROOT / "src" / "llm"))
from clients import llm, LLMError  # noqa: E402

TEST = ROOT / "data" / "pairs_test.jsonl"
RESULTS = ROOT / "results"

JUDGE_PROMPT = """Classify the logical relation between clause pairs from Maharashtra Government Resolutions.

Labels:
- "contradiction": both cannot be in force together (different amounts/percentages, different dates/deadlines, reversed eligibility, different authority/procedure, different scope for the same matter)
- "consistent": paraphrase, subset restatement, or consistent elaboration of the same rule
- "neutral": unrelated matters, no logical relation

Examples:
PAIR: A) The scholarship shall be Rs. 10,000 per student per annum. B) Each eligible student shall receive an annual scholarship of Rs. 25,000. -> contradiction
PAIR: A) Applications must be submitted by 31 March 2024. B) The last date for submission of applications is 31 March 2024. -> consistent
PAIR: A) The committee shall meet quarterly. B) Fee reimbursement is limited to unaided institutions. -> neutral

For each numbered pair output JSON: {{"results": [{{"pair": <n>, "label": "..."}}]}}
Output ONLY the JSON.

{pairs}"""


def judge(provider, pairs, batch=5, sleep=4.0):
    preds = [None] * len(pairs)
    for s in range(0, len(pairs), batch):
        chunk_ = pairs[s:s + batch]
        listing = "\n".join(
            f"PAIR {i}\nA) {p['premise'][:600]}\nB) {p['hypothesis'][:600]}\n"
            for i, p in enumerate(chunk_, 1)
        )
        prompt = JUDGE_PROMPT.format(pairs=listing)
        t0 = time.monotonic()
        try:
            data = None
            for attempt in (1, 2):
                # attempt 2 bypasses the cache READ but stores its result —
                # a malformed response must never be replayed from disk
                raw = llm(prompt, provider=provider, temperature=0.0,
                          max_tokens=2048, json_mode=True, refresh=(attempt == 2))
                m = re.search(r"\{.*\}", raw, re.DOTALL)
                try:
                    data = json.loads(m.group(0) if m else raw)
                    break
                except (json.JSONDecodeError, ValueError):
                    if attempt == 2:
                        raise
            for item in data.get("results", []):
                try:
                    pn = int(item.get("pair", 0))
                except (TypeError, ValueError):
                    continue  # one bad entry must not void the rest of the batch
                idx = s + pn - 1
                lab = str(item.get("label", "")).lower()
                # in-batch bounds: a missing/0/global pair id must never write
                # into another batch's slot (silent misassignment)
                if s <= idx < s + len(chunk_) and lab in ("contradiction", "consistent", "neutral"):
                    preds[idx] = lab
        except (LLMError, json.JSONDecodeError, ValueError) as e:
            print(f"  batch {s}: {str(e)[:100]}", flush=True)
        # cache-replayed batches return in ms with no API hit — skip the pacing sleep
        time.sleep(sleep if time.monotonic() - t0 > 1.0 else 0.05)
        if (s // batch) % 10 == 0:
            print(f"[{provider}] {s + len(chunk_)}/{len(pairs)}", flush=True)
    return preds


def metrics(rows, preds):
    from sklearn.metrics import classification_report, f1_score
    keep = [(r["label"], p) for r, p in zip(rows, preds) if p]
    y, yh = [k[0] for k in keep], [k[1] for k in keep]
    rep = classification_report(y, yh, output_dict=True, zero_division=0)
    out = {"macro_f1": round(f1_score(y, yh, average="macro"), 4),
           "n_judged": len(keep), "n_total": len(rows), "report": rep}
    # cross-generator breakdown
    by_gen = defaultdict(lambda: ([], []))
    for r, p in zip(rows, preds):
        if p:
            by_gen[r.get("generator", "?")][0].append(r["label"])
            by_gen[r.get("generator", "?")][1].append(p)
    out["by_generator_macro_f1"] = {
        g: round(f1_score(ys, ps, average="macro"), 4)
        for g, (ys, ps) in by_gen.items() if len(set(ys)) > 1
    }
    return out


def main():
    import os
    rows = [json.loads(l) for l in TEST.read_text(encoding="utf-8").splitlines()]
    RESULTS.mkdir(exist_ok=True)
    if os.environ.get("LLM_MODE", "").lower() == "ollama":
        providers = [("ollama", "ollama-local", 1.0)]  # routed to ollama
    else:
        pacing = {"gemini": 6.5, "groq": 16.0}  # tuned to each free tier
        wanted = os.environ.get("EVAL_PROVIDERS", "gemini,groq").split(",")
        providers = [(p, p, pacing[p]) for p in wanted if p in pacing]
    for provider, label, sleep_s in providers:
        print(f"=== zero-shot {label} on {len(rows)} pairs (sleep {sleep_s}s)", flush=True)
        preds = judge(provider, rows, sleep=sleep_s)
        m = metrics(rows, preds)
        p = RESULTS / f"metrics_zeroshot_{label}.json"
        p.write_text(json.dumps(m, indent=2), encoding="utf-8")
        print(f"{label}: macro-F1={m['macro_f1']} (judged {m['n_judged']}/{m['n_total']}) "
              f"by-gen={m['by_generator_macro_f1']} -> {p}", flush=True)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
